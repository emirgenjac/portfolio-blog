-- Baseline schema matching Admin + BlogPost JPA entities.
-- No seed data (admin passwords must not live in git).

CREATE TABLE admin (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255),
    password   VARCHAR(255),
    created_at TIMESTAMP(6),
    updated_at TIMESTAMP(6)
);

CREATE TABLE blog_post (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(255),
    tagline         VARCHAR(255),
    content         TEXT,
    cover_image_url TEXT,
    author          VARCHAR(255),
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6),
    admin_id        INTEGER REFERENCES admin (id)
);
